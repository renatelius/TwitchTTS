"""Сравнение имён: без регистра, пробелов и ё.

Отдельный лист без импортов: им пользуются и голоса, и записи эмоций,
поэтому он не должен тянуть за собой чистку текста.
"""


def norm_key(name):
    """Ключ для сравнения имён голосов: без регистра, пробелов и ё."""
    name = name.lower().replace("ё", "е")
    return "".join(ch for ch in name if ch.isalnum())
